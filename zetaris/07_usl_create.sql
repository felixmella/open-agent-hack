-- FactSync Chile: the Unified Semantic Layer (USL) over every source.
-- Run as an ADMIN user after 01-05:
--   .venv\Scripts\python scripts\zetaris_sql.py zetaris\07_usl_create.sql --dry-run
--   .venv\Scripts\python scripts\zetaris_sql.py zetaris\07_usl_create.sql
-- One statement per request; the multi-table COMPILE USL is one statement
-- (the runner sends the lines between BEGIN/END STATEMENT whole).
--
-- USL comuna_population, in namespace lightning.metastore.factsync:
--   comuna            the 346 comunas, as INE's Census 2024 lists them: the
--                     system of record every other table points to.
--   official_figure   every official INE figure (Census 2024, 2017 and 2002,
--                     projections 2002-2035, the Census 2017 urban/rural
--                     split), one row per series, comuna, scope and year.
--   population_claim  every population figure Wikidata and the Spanish and
--                     English Wikipedia infoboxes give, as published.
-- Both fact tables reference comuna(cut). Data-quality rules: the key and
-- foreign-key constraints (generated by Zetaris), plus three registered rules:
--   cut_is_code         comuna.cut is a five-digit code
--   population_positive official_figure.population > 0 (zero allowed for an
--                       urban or rural part)
--   figure_is_a_number  population_claim.value could be read as a number
--
-- Each table activates from the factsync views the agents already read (01-04),
-- so the USL and the agents see the same governed SQL. Checks: 07_usl_select.sql.
-- The USL's DDL parser rejects a column named `source` ("Invalid DDL statement"),
-- so the source column is source_name here.
-- Syntax: the Zetaris USL User Guide via getting-started (open_data/usl).
-- =============================================================================

CREATE NAMESPACE IF NOT EXISTS lightning.metastore;
CREATE NAMESPACE IF NOT EXISTS lightning.metastore.factsync;

-- BEGIN STATEMENT
COMPILE USL IF NOT EXISTS comuna_population DEPLOY NAMESPACE lightning.metastore.factsync DDL
CREATE TABLE comuna (
    cut varchar(5) NOT NULL PRIMARY KEY,
    comuna varchar(100) NOT NULL,
    region varchar(100)
);
CREATE TABLE official_figure (
    figure_id varchar(80) NOT NULL PRIMARY KEY,
    cut varchar(5) NOT NULL FOREIGN KEY REFERENCES comuna(cut),
    series varchar(40) NOT NULL,
    source_name varchar(40),
    definition varchar(20),
    scope varchar(20),
    reference_year int,
    population bigint
);
CREATE TABLE population_claim (
    claim_id varchar(200) NOT NULL PRIMARY KEY,
    cut varchar(5) NOT NULL FOREIGN KEY REFERENCES comuna(cut),
    source_name varchar(20) NOT NULL,
    stated_year int,
    value_raw varchar(2000),
    value bigint,
    claim_ref varchar(100),
    rank varchar(20)
);
-- END STATEMENT

UPDATE USL lightning.metastore.factsync.comuna_population SET DESCRIPTION 'FactSync Chile: every comuna population figure, official (INE) and published (Wikidata, Wikipedia ES/EN), keyed by comuna code, with data-quality rules.';
UPDATE USL lightning.metastore.factsync.comuna_population.comuna SET TABLE DESCRIPTION 'The 346 comunas as INE Census 2024 lists them: the system of record for comuna codes.';
UPDATE USL lightning.metastore.factsync.comuna_population.official_figure SET TABLE DESCRIPTION 'Every official INE population figure: Census 2024, 2017, 2002, projections 2002-2035 (base 2017), Census 2017 urban and rural.';
UPDATE USL lightning.metastore.factsync.comuna_population.population_claim SET TABLE DESCRIPTION 'Every population figure published by Wikidata and the Spanish and English Wikipedia infoboxes, as published.';

-- NOT NULL columns are wrapped in COALESCE: activation requires the query's
-- columns to be non-nullable too. A missing value becomes '' and fails the
-- key and foreign-key rules, where it shows up as invalid instead of vanishing.
ACTIVATE USL TABLE lightning.metastore.factsync.comuna_population.comuna AS
SELECT coalesce(cut, '') AS cut, coalesce(comuna, '') AS comuna, region
FROM factsync.ine_census2024;

ACTIVATE USL TABLE lightning.metastore.factsync.comuna_population.official_figure AS
SELECT coalesce(concat_ws('|', series, cut, scope, cast(reference_year AS string)), '') AS figure_id,
       coalesce(cut, '') AS cut, coalesce(series, '') AS series, source AS source_name, definition, scope,
       cast(reference_year AS int) AS reference_year,
       cast(population AS bigint) AS population
FROM factsync.official_population;

ACTIVATE USL TABLE lightning.metastore.factsync.comuna_population.population_claim AS
SELECT coalesce(concat_ws('|', source, coalesce(cut, ''), coalesce(claim_ref, '')), '') AS claim_id,
       coalesce(cut, '') AS cut,
       coalesce(source, '') AS source_name,
       cast(stated_year AS int) AS stated_year,
       substr(value_raw, 1, 2000) AS value_raw,
       cast(value AS bigint) AS value,
       claim_ref,
       rank
FROM factsync.population_picture
WHERE source_kind = 'commons';

REGISTER DQ cut_is_code TABLE lightning.metastore.factsync.comuna_population.comuna AS cut RLIKE '^[0-9]{5}$';
-- population_positive allows zero for the urban and rural parts: a fully urban comuna has no rural population.
-- Its first version (population > 0) flagged exactly those 53 real zeros, and was corrected with UPDATE DQ.
REGISTER DQ population_positive TABLE lightning.metastore.factsync.comuna_population.official_figure AS population > 0 OR (scope IN ('urban', 'rural') AND population = 0);
REGISTER DQ figure_is_a_number TABLE lightning.metastore.factsync.comuna_population.population_claim AS value IS NOT NULL;

