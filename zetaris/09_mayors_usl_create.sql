-- =============================================================================
-- FactSync Chile: a second Unified Semantic Layer (USL), for mayors.
-- Run as an ADMIN user after 07 and 08:
--   .venv\Scripts\python scripts\zetaris_sql.py zetaris\09_mayors_usl_create.sql --dry-run
--   .venv\Scripts\python scripts\zetaris_sql.py zetaris\09_mayors_usl_create.sql
-- One statement per request; the multi-table COMPILE USL is one statement.
--
-- USL comuna_mayor, in namespace lightning.metastore.factsync:
--   comuna            the 346 comunas, as INE's Census 2024 lists them. A USL of
--                     its own (foreign keys across two USLs are untested), so it
--                     has its own copy of the comuna list.
--   election_result   every candidate in SERVEL's mayoral elections 2012, 2016,
--                     2021 and 2024: votes, party, pact, and whether elected.
--   mayor_claim       the mayor each public source names: the Spanish and
--                     English Wikipedia infoboxes, and Wikidata's head of
--                     government statements (P6), as published (one row per
--                     statement: Wikidata repeats a statement per reference).
-- Both fact tables reference comuna(cut). Data-quality rules: the key and
-- foreign-key constraints (generated by Zetaris), plus four registered rules:
--   comuna_code_5_digits  comuna.cut is a five-digit code
--   votes_not_negative    election_result.votes >= 0
--   elected_is_flag       election_result.elected is 'true' or 'false'
--   mayor_named           mayor_claim.name_raw names someone (an empty infobox
--                         field fails it)
-- Exactly one winner per comuna and election can't be a row rule; a query in
-- 09_mayors_usl_select.sql checks it.
-- Lessons from 07 kept here: no column named `source` (the DDL parser rejects
-- it), and COALESCE on NOT NULL columns in each activation query.
-- =============================================================================

CREATE NAMESPACE IF NOT EXISTS lightning.metastore;
CREATE NAMESPACE IF NOT EXISTS lightning.metastore.factsync;

-- BEGIN STATEMENT
COMPILE USL IF NOT EXISTS comuna_mayor DEPLOY NAMESPACE lightning.metastore.factsync DDL
CREATE TABLE comuna (
    cut varchar(5) NOT NULL PRIMARY KEY,
    comuna varchar(100) NOT NULL,
    region varchar(100)
);
CREATE TABLE election_result (
    result_id varchar(300) NOT NULL PRIMARY KEY,
    cut varchar(5) NOT NULL FOREIGN KEY REFERENCES comuna(cut),
    election_year int NOT NULL,
    election_date varchar(10),
    candidate varchar(200) NOT NULL,
    first_surname varchar(100),
    party varchar(100),
    pact varchar(100),
    votes bigint,
    elected varchar(5)
);
CREATE TABLE mayor_claim (
    claim_id varchar(200) NOT NULL PRIMARY KEY,
    cut varchar(5) NOT NULL FOREIGN KEY REFERENCES comuna(cut),
    source_name varchar(20) NOT NULL,
    name_raw varchar(2000),
    claim_ref varchar(100),
    start_time varchar(10),
    end_time varchar(10),
    rank varchar(20)
);
-- END STATEMENT

UPDATE USL lightning.metastore.factsync.comuna_mayor SET DESCRIPTION 'FactSync Chile: who SERVEL says was elected mayor of each comuna (2012-2024), and who Wikidata and the Spanish and English Wikipedias say the mayor is, keyed by comuna code, with data-quality rules.';
UPDATE USL lightning.metastore.factsync.comuna_mayor.comuna SET TABLE DESCRIPTION 'The 346 comunas as INE Census 2024 lists them: the system of record for comuna codes.';
UPDATE USL lightning.metastore.factsync.comuna_mayor.election_result SET TABLE DESCRIPTION 'Every candidate in SERVEL mayoral elections 2012, 2016, 2021 and 2024, with votes, party, pact and whether elected.';
UPDATE USL lightning.metastore.factsync.comuna_mayor.mayor_claim SET TABLE DESCRIPTION 'The mayor named by the Spanish and English Wikipedia infoboxes and by Wikidata (P6), as published.';

ACTIVATE USL TABLE lightning.metastore.factsync.comuna_mayor.comuna AS
SELECT coalesce(cut, '') AS cut, coalesce(comuna, '') AS comuna, region
FROM factsync.ine_census2024;

ACTIVATE USL TABLE lightning.metastore.factsync.comuna_mayor.election_result AS
SELECT coalesce(concat_ws('|', cast(year AS string), cut, lista, nombres, primer_apellido, segundo_apellido), '') AS result_id,
       coalesce(cut, '') AS cut,
       coalesce(year, 0) AS election_year,
       election_date,
       coalesce(concat_ws(' ', nombres, primer_apellido, segundo_apellido), '') AS candidate,
       primer_apellido AS first_surname,
       partido AS party,
       pacto AS pact,
       votos AS votes,
       cast(elected AS string) AS elected
FROM factsync.servel_mayors;

ACTIVATE USL TABLE lightning.metastore.factsync.comuna_mayor.mayor_claim AS
SELECT DISTINCT coalesce(concat_ws('|', 'Wikidata', coalesce(cut, ''), coalesce(statement_id, wikidata_item)), '') AS claim_id,
       coalesce(cut, '') AS cut,
       'Wikidata' AS source_name,
       coalesce(person_label_es, person_label_en, person_item) AS name_raw,
       statement_id AS claim_ref,
       start_time,
       end_time,
       rank
FROM factsync.wikidata_mayor
UNION ALL
SELECT coalesce(concat_ws('|', 'Wikipedia ES', coalesce(cut, ''), cast(revid AS string)), ''),
       coalesce(cut, ''), 'Wikipedia ES', substr(name_raw, 1, 2000), cast(revid AS string),
       cast(NULL AS string), cast(NULL AS string), cast(NULL AS string)
FROM factsync.eswiki_mayor
UNION ALL
SELECT coalesce(concat_ws('|', 'Wikipedia EN', coalesce(cut, ''), cast(revid AS string)), ''),
       coalesce(cut, ''), 'Wikipedia EN', substr(name_raw, 1, 2000), cast(revid AS string),
       cast(NULL AS string), cast(NULL AS string), cast(NULL AS string)
FROM factsync.enwiki_mayor;

REGISTER DQ comuna_code_5_digits TABLE lightning.metastore.factsync.comuna_mayor.comuna AS cut RLIKE '^[0-9]{5}$';
REGISTER DQ votes_not_negative TABLE lightning.metastore.factsync.comuna_mayor.election_result AS votes >= 0;
REGISTER DQ elected_is_flag TABLE lightning.metastore.factsync.comuna_mayor.election_result AS elected IN ('true', 'false');
REGISTER DQ mayor_named TABLE lightning.metastore.factsync.comuna_mayor.mayor_claim AS name_raw IS NOT NULL AND trim(name_raw) <> '';

