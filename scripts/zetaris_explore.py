"""Run a Zetaris _select.sql file live and record each query with its real result, as Markdown.

Usage:  .venv\\Scripts\\python scripts\\zetaris_explore.py zetaris\\06_explore_select.sql --out docs\\zetaris\\exploration.md
        .venv\\Scripts\\python scripts\\zetaris_explore.py zetaris\\07_usl_select.sql --admin --out docs\\zetaris\\usl.md

In the file, a `-- Q: <question>` line titles the statement after it; other comment lines are skipped; a statement ends
with a semicolon at the end of a line. Queries run with the app's read-only key (ZETARIS_API_KEY), or with the admin
key (ZETARIS_ADMIN_API_KEY) when --admin is given: USL and DQ commands need a privileged user. No key is ever printed.
"""
import argparse
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

from dotenv import load_dotenv

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.adapters.zetaris import ZetarisClient, ZetarisError  # noqa: E402

load_dotenv()


def queries(path):
    """[(question, sql)] in file order."""
    found, question, lines = [], None, []
    for line in open(path, encoding="utf-8"):
        stripped = line.strip()
        if stripped.startswith("-- Q:"):
            question = stripped[5:].strip()
        elif stripped.startswith("--") or not stripped and not lines:
            continue
        else:
            lines.append(line)
            if stripped.endswith(";"):
                found.append((question, "".join(lines).strip().rstrip(";").strip()))
                question, lines = None, []
    if "".join(lines).strip():
        found.append((question, "".join(lines).strip()))
    return found


def cell(value):
    text = "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")
    return text if len(text) <= 120 else text[:117] + "..."


def table(columns, rows):
    if not columns:
        return "_(no columns returned)_\n"
    out = ["| " + " | ".join(cell(c) for c in columns) + " |", "|" + "---|" * len(columns)]
    out += ["| " + " | ".join(cell(row.get(c)) for c in columns) + " |" for row in rows]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("file")
    parser.add_argument("--out", required=True)
    parser.add_argument("--admin", action="store_true", help="use the admin key (USL and DQ commands)")
    parser.add_argument("--rows", type=int, default=12, help="rows to show per query")
    args = parser.parse_args()

    key = os.environ.get("ZETARIS_ADMIN_API_KEY" if args.admin else "ZETARIS_API_KEY", "")
    client = ZetarisClient(os.environ.get("ZETARIS_REST_URL", "http://localhost:8888/api/v1.0"),
                           os.environ.get("ZETARIS_ORG_ID", "1"), key, timeout=180.0)
    who = "admin user" if args.admin else "the app's read-only user"
    started = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    parts = [f"<!-- Generated by scripts/zetaris_explore.py from {Path(args.file).as_posix()}; do not edit by hand. -->\n",
             f"Run live against Zetaris on {started}, as {who}. Each result shows at most {args.rows} rows.\n"]
    failures = 0
    for number, (question, sql) in enumerate(queries(args.file), 1):
        title = question or "Query"
        parts.append(f"\n### {number}. {title}\n\n```sql\n{sql}\n```\n")
        try:
            result = client.query(sql, limit=max(args.rows, 1))
        except ZetarisError as exc:
            failures += 1
            parts.append(f"\n**Failed:** {cell(str(exc))}\n")
            print(f"[{number}] FAIL {title}: {str(exc)[:200]}")
            continue
        shown = result.rows[: args.rows]
        parts.append("\n" + table(result.columns, shown))
        more = f", {result.total} in all" if result.total > len(shown) else ""
        parts.append(f"\n_{len(shown)} row(s) shown{more}; {result.elapsed_ms} ms._\n")
        print(f"[{number}] OK   {title} ({len(shown)} rows, {result.elapsed_ms} ms)")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("".join(parts), encoding="utf-8")
    print(f"wrote {args.out}; {failures} failure(s)")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
