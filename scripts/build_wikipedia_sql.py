"""Generate zetaris/03_wikipedia_create.sql: the Spanish and English Wikipedia articles of every current comuna
as Zetaris REST tables, plus views that flatten them and key them by CUT.

Usage:  .venv\\Scripts\\python scripts\\build_wikipedia_sql.py [--batch-size 50]

REST table endpoints are fixed when they are registered, so articles are fetched in batches of up to 50 titles
(the MediaWiki API limit). Each batch is requested once here to check that every page comes back with content
and the result isn't truncated. Needs ZETARIS_USER_AGENT (Wikimedia requires an identifying User-Agent).
"""
import argparse
import os
import sys
import urllib.parse
from pathlib import Path

import httpx
from dotenv import load_dotenv

load_dotenv()

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "zetaris" / "03_wikipedia_create.sql"
UA_PLACEHOLDER = "YOUR_APP_NAME YOUR_CONTACT_EMAIL"

SITELINKS_SPARQL = """SELECT ?comuna ?cut ?label_es ?es_title ?en_title WHERE {
  ?comuna wdt:P31 wd:Q1840161. FILTER NOT EXISTS { ?comuna wdt:P576 ?dissolved }
  OPTIONAL { ?comuna wdt:P6929 ?cut }
  OPTIONAL { ?comuna rdfs:label ?label_es FILTER(lang(?label_es)='es') }
  OPTIONAL { ?es schema:about ?comuna; schema:isPartOf <https://es.wikipedia.org/>; schema:name ?es_title }
  OPTIONAL { ?en schema:about ?comuna; schema:isPartOf <https://en.wikipedia.org/>; schema:name ?en_title }
}"""


def sparql_url(query):
    return "https://query.wikidata.org/sparql?" + urllib.parse.urlencode({"query": " ".join(query.split()), "format": "json"})


def articles_url(lang, titles):
    return f"https://{lang}.wikipedia.org/w/api.php?" + urllib.parse.urlencode({
        "action": "query", "prop": "revisions", "rvprop": "content|ids|timestamp", "rvslots": "main",
        "format": "json", "formatversion": "2", "titles": "|".join(titles),
    })


def rest_table(name, url, user_agent_header):
    header = f'\n    user-agent "{UA_PLACEHOLDER}"\n' if user_agent_header else "\n"
    return (f'CREATE LIGHTNING REST TABLE {name} FROM FACTSYNC_REST REQUEST(\n'
            f'    endpoint "{url}",\n    method "get",\n    response_type "json",\n    http_encoding "URLENCODED"\n'
            f') HEADER ({header}) BODY ();\n')


def check_batch(client, lang, titles):
    body = client.get(articles_url(lang, titles), timeout=120).json()
    pages = body.get("query", {}).get("pages", [])
    with_content = [p for p in pages if p.get("revisions")]
    if "continue" in body or len(with_content) != len(titles):
        missing = sorted(set(titles) - {p["title"] for p in with_content})
        sys.exit(f"{lang} batch incomplete (continue={'continue' in body}, missing={missing[:5]}); try a smaller --batch-size")
    return sum(len(p["revisions"][0]["slots"]["main"]["content"]) for p in with_content)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--batch-size", type=int, default=50)
    args = parser.parse_args()
    user_agent = os.environ.get("ZETARIS_USER_AGENT", "")
    if "@" not in user_agent:
        sys.exit("ZETARIS_USER_AGENT must name an app and a contact e-mail")
    client = httpx.Client(headers={"User-Agent": user_agent})

    rows = client.get(sparql_url(SITELINKS_SPARQL), headers={"Accept": "application/sparql-results+json"},
                      timeout=120).json()["results"]["bindings"]
    titles = {"es": sorted({r["es_title"]["value"] for r in rows if "es_title" in r}),
              "en": sorted({r["en_title"]["value"] for r in rows if "en_title" in r})}

    parts = [f"""-- =============================================================================
-- FactSync Chile: Spanish and English Wikipedia articles of every current comuna.
-- GENERATED by scripts/build_wikipedia_sql.py; regenerate rather than edit.
-- Run as an ADMIN user after 01 and 02. One statement per request.
--
-- Sources
--   Wikidata sitelinks: comuna item, CUT and article titles (CC0).
--   Wikipedia ES/EN: latest revision wikitext via the MediaWiki API, in batches
--     of up to {args.batch_size} titles ({len(titles['es'])} ES, {len(titles['en'])} EN articles). Text is CC BY-SA 4.0.
--   Wikimedia requires an identifying User-Agent: filled from ZETARIS_USER_AGENT.
-- =============================================================================

""", rest_table("wikidata_comunas_raw", sparql_url(SITELINKS_SPARQL), True), """
CREATE OR REPLACE SCHEMASTORE VIEW wikidata_comunas WITH CONTAINER factsync AS
SELECT
    b.comuna.value AS wikidata_item,
    b.cut.value AS cut,
    b.label_es.value AS label_es,
    b.es_title.value AS es_title,
    b.en_title.value AS en_title
FROM factsync_rest.wikidata_comunas_raw
LATERAL VIEW explode(results.bindings) AS b;
"""]
    for lang in ("es", "en"):
        batches = [titles[lang][i:i + args.batch_size] for i in range(0, len(titles[lang]), args.batch_size)]
        tables = []
        for n, batch in enumerate(batches, 1):
            size = check_batch(client, lang, batch)
            name = f"{lang}wiki_batch_{n:02d}_raw"
            tables.append(name)
            print(f"{name}: {len(batch)} articles, {size / 1e6:.1f} MB of wikitext")
            parts.append("\n" + rest_table(name, articles_url(lang, batch), True))
        union = "\nUNION ALL\n".join(
            f"SELECT p.pageid, p.title, p.revisions[0].revid AS revid, p.revisions[0].timestamp AS revision_timestamp,\n"
            f"       p.revisions[0].slots.main.content AS wikitext\n"
            f"FROM factsync_rest.{t} LATERAL VIEW explode(query.pages) AS p" for t in tables)
        parts.append(f"""
CREATE OR REPLACE SCHEMASTORE VIEW {lang}wiki_articles WITH CONTAINER factsync AS
SELECT w.cut, w.wikidata_item, a.pageid, a.title, a.revid, a.revision_timestamp, a.wikitext
FROM (
{union}
) a
LEFT JOIN factsync.wikidata_comunas w ON w.{lang}_title = a.title;
""")
    OUTPUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
